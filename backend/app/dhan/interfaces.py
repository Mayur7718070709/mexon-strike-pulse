from datetime import date, datetime
from typing import Any, AsyncIterator, Protocol


class MarketDataProvider(Protocol):
    name: str

    async def get_market_quotes(self, instruments: dict[str, list[int]], kind: str = "ltp") -> dict[str, Any]: ...
    async def get_option_chain(self, underlying_scrip: int, underlying_segment: str, expiry: date) -> dict[str, Any]: ...
    async def get_expiries(self, underlying_scrip: int, underlying_segment: str) -> dict[str, Any]: ...
    async def get_historical_candles(self, security_id: str, exchange_segment: str, instrument: str, from_date: date | datetime, to_date: date | datetime, interval: str | None = None, oi: bool = False, expiry_code: int | None = None) -> dict[str, Any]: ...
    async def get_expired_options(self, *, exchange_segment: str, security_id: str, instrument: str, interval: str, expiry_flag: str, expiry_code: int, strike: str, option_type: str, required_data: list[str], from_date: date, to_date: date) -> dict[str, Any]: ...
    async def get_instrument_master(self, detailed: bool = False) -> dict[str, Any]: ...
    def stream_market_data(self, instruments: list[tuple[str, str]], mode: str = "ticker") -> AsyncIterator[dict[str, Any]]: ...
